// kfflang, kfflib and kffmod are subprojects because JarJar wants a Maven Dependency when bundling a JAR
subprojects {
    @Suppress("AvoidApplyPluginMethod")
    apply(plugin = "java-library")

    group = rootProject.group
    version = rootProject.version

    extensions.configure<JavaPluginExtension> {
        toolchain.languageVersion.set(JavaLanguageVersion.of(25))
    }

    // kfflang -> langJar, kfflib -> libJar, kffmod -> modJar
    val rootJar = rootProject.tasks.named<Jar>(name.removePrefix("kff") + "Jar")

    // copy the artifacts from root into each subproject
    for (elements in listOf("apiElements", "runtimeElements")) {
        configurations.named(elements) {
            outgoing.artifacts.clear()
            outgoing.artifact(rootJar)
        }
    }

    // we don't need the empty subproject JAR generated by java-library, the real JAR is from rootJar
    tasks.named("jar") {
        enabled = false
    }
}
